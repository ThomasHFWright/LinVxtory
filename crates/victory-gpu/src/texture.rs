fn staging_subresource(data: &mut [u8], offset: u64, padded_bytes: usize) -> Option<&mut [u8]> {
    let offset = usize::try_from(offset).ok()?;
    let end = offset.saturating_add(padded_bytes).min(data.len());
    data.get_mut(offset..end)
}

